/// Marker substituted by the project layer (user types) during generation.
/// These lines live in `runa_base.luau` and are replaced by [`render_runa_project`].
const MARKER_TYPES: &str = "-- @@runa:types@@\n";
const MARKER_MARKERS: &str = "-- @@runa:markers@@\n";
const MARKER_RETURN: &str = "-- @@runa:return@@\n";

/// The engine's committed base file, embedded so project generation never needs
/// to locate the engine on disk.
const RUN_BASE: &str = include_str!("../scripts/runa_base.luau");

/// The generated sections for one layer (`builtin == true` for the engine base,
/// `false` for a user project).
struct Sections {
    /// `export type` definitions (aux types first, then components), sorted by
    /// name so generation is deterministic.
    types: String,
    /// `local Name: Name = {} :: Name;` class markers, sorted.
    markers: String,
    /// `     Name = Name,` class fields + `name = function(...) ... end,` stubs.
    return_fields: String,
}

fn collect_sections(builtin: bool) -> Sections {
    let mut aux: Vec<(String, String)> = iter::<ScriptAuxType>()
        .filter(|a| a.builtin == builtin)
        .map(|a| (a.name.to_string(), a.type_def.to_string()))
        .collect();
    let mut comps: Vec<(String, String)> = iter::<ScriptType>()
        .filter(|t| t.builtin == builtin)
        .map(|t| (t.name.to_string(), t.type_def.to_string()))
        .collect();
    aux.sort_by(|a, b| a.0.cmp(&b.0));
    comps.sort_by(|a, b| a.0.cmp(&b.0));

    let mut types = String::new();
    for (_, def) in aux.iter().chain(comps.iter()) {
        types.push_str(def);
        types.push('\n');
    }
    if !types.is_empty() {
        types.push('\n');
    }

    let mut markers = String::new();
    for (name, _) in &comps {
        markers.push_str(&format!("local {name}: {name} = {{}} :: {name};\n"));
    }

    let mut return_fields = String::new();
    for (name, _) in &comps {
        return_fields.push_str(&format!("    {name} = {name},\n"));
    }

    Sections {
        types,
        markers,
        return_fields,
    }
}

/// Render the engine's immutable base module: every `#[script(builtin)]` type
/// plus the `-- @@runa:*@@` markers where a user project's own types get spliced in.
pub fn render_runa_base() -> String {
    let builtin = collect_sections(true);

    let mut s = String::new();
    s.push_str(&header());
    s.push_str(&math_types());
    s.push_str(&format!("export type KeyCode = {}\n\n", keycode_union()));
    s.push_str(&script_input());
    s.push_str("export type ScriptEvent = { name: string, x: number, y: number }\n\n");

    s.push_str(&builtin.types);
    s.push_str(MARKER_TYPES);
    s.push_str(&builtin.markers);
    s.push_str(MARKER_MARKERS);

    s.push_str(
        "export type ScriptContext = {\n    entity: number,\n    dt: number,\n    input: ScriptInput,\n    components: { [string]: any },\n    events: { ScriptEvent },\n    events_in: { ScriptEvent },\n",
    );
    s.push_str(
        "    GetComponent: <T>(self: ScriptContext, component: T) -> T,\n    HasComponent: <T>(self: ScriptContext, component: T) -> boolean,\n    AddComponent: <T>(self: ScriptContext, component: T, value: any) -> (),\n    RemoveComponent: <T>(self: ScriptContext, component: T) -> (),\n    Spawn: (self: ScriptContext, path: string) -> (),\n    Destroy: (self: ScriptContext, entity: number) -> (),\n}\n\n",
    );

    s.push_str("return {\n");
    s.push_str(&builtin.return_fields);
    s.push_str(MARKER_RETURN);
    s.push_str("    vec2 = function(x: number, y: number): Vec2 return { x = x, y = y } end,\n");
    s.push_str("    vec3 = function(x: number, y: number, z: number): Vec3 return { x = x, y = y, z = z } end,\n");
    s.push_str("    vec4 = function(x: number, y: number, z: number, w: number): Vec4 return { x = x, y = y, z = z, w = w } end,\n");
    s.push_str("    quat = function(x: number, y: number, z: number, w: number): Quat return { x = x, y = y, z = z, w = w } end,\n");
    s.push_str("    normalize2 = function(v: Vec2): Vec2 return v end,\n");
    s.push_str("    normalize3 = function(v: Vec3): Vec3 return v end,\n");
    s.push_str("    length2 = function(v: Vec2): number return 0 end,\n");
    s.push_str("    length3 = function(v: Vec3): number return 0 end,\n");
    s.push_str("    pi = 3.141592653589793,\n");
    s.push_str("    cos = function(x: number): number return 0 end,\n");
    s.push_str("    sin = function(x: number): number return 0 end,\n");
    s.push_str("    tan = function(x: number): number return 0 end,\n");
    s.push_str("    atan2 = function(y: number, x: number): number return 0 end,\n");
    s.push_str("    sqrt = function(x: number): number return 0 end,\n");
    s.push_str("    abs = function(x: number): number return 0 end,\n");
    s.push_str("    floor = function(x: number): number return 0 end,\n");
    s.push_str("    ceil = function(x: number): number return 0 end,\n");
    s.push_str("    round = function(x: number): number return 0 end,\n");
    s.push_str("    sign = function(x: number): number return 0 end,\n");
    s.push_str("    pow = function(x: number, y: number): number return 0 end,\n");
    s.push_str("    max = function(a: number, b: number): number return 0 end,\n");
    s.push_str("    min = function(a: number, b: number): number return 0 end,\n");
    s.push_str("    clamp = function(x: number, lo: number, hi: number): number return 0 end,\n");
    s.push_str("    rad = function(x: number): number return 0 end,\n");
    s.push_str("    deg = function(x: number): number return 0 end,\n");
    s.push_str("}\n");
    s
}

/// Render a *user project's* `runa.luau`: the engine base spliced together with
/// every non-builtin type / function registered in this binary (via `inventory`).
pub fn render_runa_project() -> String {
    let user = collect_sections(false);
    RUN_BASE
        .replace(MARKER_TYPES, &user.types)
        .replace(MARKER_MARKERS, &user.markers)
        .replace(MARKER_RETURN, &user.return_fields)
}

/// Regenerate `scripts/runa_base.luau` inside the engine. Run the
/// `gen-runa-base` binary (linked against the engine) to refresh it after
/// changing a `#[script(builtin)]` component.
pub fn write_runa_base(path: &std::path::Path) {
    if let Some(parent) = path.parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    let _ = std::fs::write(path, render_runa_base());
}

/// Regenerates the Luau type-definition module (`runa.luau`) that `luau-lsp`
/// reads for autocomplete / type checking. Call this from your game's startup
/// (once) with the output path, e.g.
/// `write_luau_types(Path::new(".runa/runa.luau"))`.
///
/// The emitted file is the engine's committed base (`scripts/runa_base.luau`)
/// plus everything your binary registers as scriptable via
/// `#[derive(Scriptable)]` / aux type registrations.
pub fn write_luau_types(path: &std::path::Path) {
    if let Some(parent) = path.parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    let _ = std::fs::write(path, render_runa_project());
}

fn header() -> String {
    let mut s = String::new();
    s.push_str("-- THIS FILE IS GENERATED. DO NOT EDIT BY HAND.\n");
    s.push_str("-- The engine layer (`runa_base.luau`, built-in types) is regenerated by the\n");
    s.push_str(
        "-- `gen-runa-base` binary; your project's own types are appended from `inventory`.\n",
    );
    s.push_str("-- Read by `luau-lsp` for type checking and autocomplete.\n\n");
    s
}

fn math_types() -> String {
    "export type Vec3 = { x: number, y: number, z: number }\nexport type Vec4 = { x: number, y: number, z: number, w: number }\nexport type Vec2 = { x: number, y: number }\nexport type Quat = { x: number, y: number, z: number, w: number }\n\n".to_string()
}

fn script_input() -> String {
    let kc = keycode_names();
    let mut s = String::from("export type ScriptInput = {\n");
    for k in kc {
        s.push_str(&format!("    {k}: boolean,\n"));
    }
    s.push_str("    keys_just_pressed: { [string]: boolean },\n");
    s.push_str("    mouse_buttons_pressed: { [string]: boolean },\n");
    s.push_str("    mouse_buttons_just_pressed: { [string]: boolean },\n");
    s.push_str("    mouse_position: { x: number, y: number },\n");
    s.push_str("    mouse_delta: { x: number, y: number },\n");
    s.push_str("    mouse_wheel_delta: number,\n");
    s.push_str("    is_key_pressed: (self: ScriptInput, key: KeyCode) -> boolean,\n");
    s.push_str("    is_key_just_pressed: (self: ScriptInput, key: KeyCode) -> boolean,\n");
    s.push_str("    is_mouse_pressed: (self: ScriptInput, button: string) -> boolean,\n");
    s.push_str("    is_mouse_just_pressed: (self: ScriptInput, button: string) -> boolean,\n");
    s.push_str("    get_mouse_position: (self: ScriptInput) -> { x: number, y: number },\n");
    s.push_str("}\n\n");
    s
}

fn keycode_union() -> String {
    keycode_names()
        .iter()
        .map(|k| format!("\"{k}\""))
        .collect::<Vec<_>>()
        .join(" | ")
}

